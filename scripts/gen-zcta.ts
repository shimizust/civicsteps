/**
 * Writes lib/civic/zcta.data.ts: one interior point per ZIP Code Tabulation Area, from the
 * Census Gazetteer. Lets us turn a ZIP into districts without asking for a street address.
 *
 * Run (refresh yearly when the Census publishes a new Gazetteer):
 *   curl -sO https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip
 *   unzip 2024_Gaz_zcta_national.zip
 *   npm run gen:zcta -- 2024_Gaz_zcta_national.txt
 */
import { readFileSync, writeFileSync } from "fs";
import { basename } from "path";

const file = process.argv[2];
if (!file) throw new Error("Usage: npm run gen:zcta -- <path to *_Gaz_zcta_national.txt>");

const [header, ...rows] = readFileSync(file, "utf8").trim().split("\n");
const cols = header.split("\t").map((c) => c.trim());
const [iZip, iLat, iLng] = ["GEOID", "INTPTLAT", "INTPTLONG"].map((c) => cols.indexOf(c));
if ([iZip, iLat, iLng].includes(-1)) throw new Error(`Unexpected header: ${cols.join(", ")}`);

// 4 decimal places ≈ 11 m, plenty for an interior point.
const fmt = (n: string) => String(Number(Number(n).toFixed(4)));
const lines = rows
  .map((r) => r.split("\t").map((c) => c.trim()))
  .filter((c) => /^\d{5}$/.test(c[iZip]))
  .map((c) => `${c[iZip]} ${fmt(c[iLat])} ${fmt(c[iLng])}`)
  .sort();

writeFileSync(
  "lib/civic/zcta.data.ts",
  `// GENERATED by scripts/gen-zcta.ts from ${basename(file)} — do not edit by hand.\n` +
    `// "zip lat lng" per line: the Census interior point of each ZIP Code Tabulation Area.\n` +
    `export const ZCTA_POINTS = ${JSON.stringify(lines.join("\n"))};\n`,
);
console.log(`Wrote ${lines.length} ZCTAs`);
